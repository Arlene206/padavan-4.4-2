#ifndef PADAVAN_PPP_OPTION_VALUE_POLICY_H
#define PADAVAN_PPP_OPTION_VALUE_POLICY_H

#include <errno.h>
#include <stddef.h>
#include <stdlib.h>
#include <string.h>

/*
 * Escape values written into pppd's single-quoted option syntax.
 * Reject control characters so one configured value cannot turn into multiple
 * option lines. Custom option text has a separate mode that preserves LF/TAB.
 * Both modes fail on overflow instead of returning raw or truncated input.
 */
static int
ppp_option_escape_internal(const char *value, char *out, size_t out_size,
                           int allow_line_breaks)
{
	const unsigned char *src;
	size_t needed, extra, used;

	if (!out || out_size == 0) {
		errno = EINVAL;
		return -1;
	}
	out[0] = '\0';
	if (!value) {
		errno = EINVAL;
		return -1;
	}

	needed = 1; /* terminating NUL */
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src < 0x20 &&
		    !(allow_line_breaks && (*src == '\n' || *src == '\t'))) {
			errno = EINVAL;
			return -1;
		}
		if (*src == 0x7f) {
			errno = EINVAL;
			return -1;
		}

		extra = (*src == '\'' || *src == '\\') ? 2U : 1U;
		if (needed > (size_t)-1 - extra) {
			errno = EOVERFLOW;
			return -1;
		}
		needed += extra;
	}

	if (needed > out_size) {
		errno = EOVERFLOW;
		return -1;
	}

	used = 0;
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src == '\'' || *src == '\\')
			out[used++] = '\\';
		out[used++] = (char)*src;
	}
	out[used] = '\0';

	return 0;
}

static int
ppp_option_value_escape(const char *value, char *out, size_t out_size)
{
	return ppp_option_escape_internal(value, out, out_size, 0);
}

/* WAN callback identity is generated by RC and cannot be overridden by the
 * user-provided free-form PPP options. Ignore comments while inspecting keys. */
static int
ppp_option_text_reject_ipparam(const char *value)
{
	static const char forbidden[] = "ipparam";
	const unsigned char *p;
	size_t key_length;
	int quoted, escaped, matches;

	if (!value) {
		errno = EINVAL;
		return -1;
	}

	p = (const unsigned char *)value;
	while (*p) {
		/* pppd getword() accepts multiple options on one physical line. */
		while (*p == ' ' || *p == '\t' || *p == '\n')
			++p;
		if (*p == '#') {
			while (*p && *p != '\n')
				++p;
			continue;
		}
		if (!*p)
			break;

		/*
		 * Follow getword() token boundaries: remove quote delimiters,
		 * preserve escaped characters and treat a comment marker outside
		 * quotes as the start of a comment. This catches quoted or adjacent
		 * fragments such as "ipparam", ip"param" and "ip"param.
		 */
		key_length = 0;
		matches = 1;
		quoted = 0;
		escaped = 0;
		while (*p) {
			unsigned char c = *p;

			if (escaped) {
				escaped = 0;
				if (c != '\n') {
					if (key_length >= sizeof(forbidden) - 1 ||
					    forbidden[key_length] != c)
						matches = 0;
					++key_length;
				}
				++p;
				continue;
			}
			if (c == '\\') {
				escaped = 1;
				++p;
				continue;
			}
			if (quoted) {
				if (c == (unsigned char)quoted) {
					quoted = 0;
				} else {
					if (key_length >= sizeof(forbidden) - 1 ||
					    forbidden[key_length] != c)
						matches = 0;
					++key_length;
				}
				++p;
				continue;
			}
			if (c == '"' || c == '\'') {
				quoted = c;
				++p;
				continue;
			}
			if (c == ' ' || c == '\t' || c == '\n' ||
			    c == '#' || c == '=')
				break;
			if (key_length >= sizeof(forbidden) - 1 ||
			    forbidden[key_length] != c)
				matches = 0;
			++key_length;
			++p;
		}

		if (matches && key_length == sizeof(forbidden) - 1) {
			errno = EPERM;
			return -1;
		}

		/* Keep rejecting the legacy key=value spelling as a safety guard. */
		if (*p == '=') {
			while (*p && *p != ' ' && *p != '\t' && *p != '\n')
				++p;
		}
	}
	return 0;
}

static int
ppp_option_text_escape(const char *value, char *out, size_t out_size)
{
	if (ppp_option_text_reject_ipparam(value) != 0) {
		if (out && out_size > 0)
			out[0] = '\0';
		return -1;
	}
	return ppp_option_escape_internal(value, out, out_size, 1);
}


/*
 * Escape NVRAM-backed multiline text without a fixed-size truncation.
 * Every input byte may require an escape prefix, so allocate the worst case.
 */
static inline int
ppp_option_text_escape_alloc(const char *value, char **out)
{
	size_t length, capacity;
	char *buffer;
	int saved_errno;

	if (!out) {
		errno = EINVAL;
		return -1;
	}
	*out = NULL;
	if (!value) {
		errno = EINVAL;
		return -1;
	}

	length = strlen(value);
	if (length > ((size_t)-1 - 1U) / 2U) {
		errno = EOVERFLOW;
		return -1;
	}
	capacity = length * 2U + 1U;
	buffer = (char *)malloc(capacity);
	if (!buffer)
		return -1;
	if (ppp_option_text_escape(value, buffer, capacity) != 0) {
		saved_errno = errno ? errno : EINVAL;
		free(buffer);
		errno = saved_errno;
		return -1;
	}

	*out = buffer;
	return 0;
}

/*
 * Copy one unquoted scalar into line-oriented L2TP config syntax.
 * These values are not shell strings: reject all control bytes, CR/LF and
 * overlong values instead of allowing one configured value to create options
 * or sections on subsequent lines.
 */
static int
ppp_config_line_value_copy(const char *value, char *out, size_t out_size)
{
	const unsigned char *src;
	size_t used;

	if (!out || out_size == 0) {
		errno = EINVAL;
		return -1;
	}
	out[0] = '\0';
	if (!value) {
		errno = EINVAL;
		return -1;
	}

	used = 0;
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src < 0x20 || *src == 0x7f) {
			out[0] = '\0';
			errno = EINVAL;
			return -1;
		}
		if (used >= out_size - 1) {
			out[0] = '\0';
			errno = EOVERFLOW;
			return -1;
		}
		out[used++] = (char)*src;
	}
	out[used] = '\0';
	return 0;
}

#endif /* PADAVAN_PPP_OPTION_VALUE_POLICY_H */
